import type { ServiceType } from '../domain/mealService';

export interface NPSData {
  score: number; // 0-10
  comment: string;
  recovered: boolean;
}

export interface ParsedPassenger {
  seat: string;
  firstName: string;
  lastName: string;
  status?: string;
  codes: string[];
  rawText: string;
  nps?: NPSData;
}

export interface FlightManifest {
  flightNumber: string;
  date: string;
  aircraftType: string;
  origin: string;
  destination: string;
  departureTime: string;
  serviceType: ServiceType;
  passengers: ParsedPassenger[];
  infantCount: number;
}

const pax = (
  seat: string,
  lastName: string,
  firstName: string,
  status?: string,
  codes: string[] = []
): ParsedPassenger => ({
  seat,
  firstName,
  lastName,
  status,
  codes: status ? [status, ...codes] : codes,
  rawText: `${seat} ${lastName}/${firstName}`,
});

const paxWithNps = (
  seat: string,
  lastName: string,
  firstName: string,
  status: string | undefined,
  codes: string[],
  nps: NPSData
): ParsedPassenger => ({
  ...pax(seat, lastName, firstName, status, codes),
  nps
});

